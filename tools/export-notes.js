// Generates the speaker notes as a Typst document from site/slides.js and
// site/notes.js, so the notes have a single source.
//
// Usage: node tools/export-notes.js            -> notes/speaker-notes.typ
//        typst compile notes/speaker-notes.typ  -> notes/speaker-notes.pdf
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const ctx = { window: {}, console };
ctx.globalThis = ctx.window;
vm.createContext(ctx);
for (const f of ['raft-sim.js', 'slides.js', 'notes.js']) {
  vm.runInContext(fs.readFileSync(path.join(ROOT, 'site', f), 'utf8'), ctx, { filename: f });
}
const { SLIDES } = ctx.window.TALK;
const NOTES = ctx.window.NOTES;

// HTML from the slides -> plain text, then escape Typst markup characters.
const plain = s => String(s || '')
  .replace(/<[^>]+>/g, '')
  .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&nbsp;/g, ' ');
const typ = s => plain(s).replace(/[\\#$*_@<>\[\]`~=\/]/g, c => '\\' + c);
const mmss = min => `${Math.floor(min)}:${String(Math.round((min % 1) * 60)).padStart(2, '0')}`;

let section = '';
let cumulative = 0;
const rows = [];
const body = [];
SLIDES.forEach((sl, i) => {
  if (sl.section != null) section = sl.section;
  const n = NOTES[sl.title] || {};
  const min = n.min || 0;
  rows.push(`  [${i + 1}], [${typ(sl.title)}${sl.optional ? ' #opt' : ''}], [${mmss(min)}], [${mmss(cumulative + min)}],`);
  cumulative += min;

  const frags = sl.frags || [];
  const steps = n.steps || [];
  const parts = [];
  parts.push(`== ${i + 1}. ${typ(sl.title)}${sl.optional ? ' #opt' : ''}`);
  parts.push(`#meta[${typ([section, sl.kicker].filter(Boolean).join(' · '))} · about ${mmss(min)} min]`);
  if (n.open) parts.push(`#opening[${typ(n.open)}]`);
  if (frags.length) {
    parts.push(frags.map((f, k) => `#click(${k + 1})[${typ(f.text)}][${typ(steps[k] || '')}]`).join('\n'));
  }
  if (n.watch) parts.push(`#watch[${typ(n.watch)}]`);
  if (sl.notes) parts.push(`#background[${typ(sl.notes)}]`);
  body.push(parts.join('\n\n'));
});

const out = `// Generated by tools/export-notes.js from site/slides.js and site/notes.js.
// Edit the notes there and regenerate; changes made here are overwritten.
#set document(title: "Raft seminar: speaker notes")
#set page(paper: "a4", margin: (x: 2cm, y: 1.8cm), numbering: "1 / 1")
#set text(font: ("DejaVu Sans", "Liberation Sans", "Arial"), size: 12pt, lang: "en")
#set par(leading: 0.85em, spacing: 1.1em, justify: false)
#show heading.where(level: 2): it => block(above: 1.6em, below: 0.6em, text(size: 16pt, weight: "bold", it.body))

#let opt = text(fill: rgb("#b7791f"), size: 0.8em, weight: "bold")[ (optional)]
#let meta(body) = text(fill: luma(110), size: 10pt, body)
#let opening(body) = block(width: 100%, inset: (left: 10pt, y: 6pt), stroke: (left: 3pt + rgb("#2b6cb0")))[
  #text(size: 9pt, weight: "bold", fill: rgb("#2b6cb0"))[WHEN THE SLIDE OPENS] \\
  #body
]
#let click(n, screen, say) = block(width: 100%, breakable: false, inset: (left: 10pt, y: 5pt), stroke: (left: 3pt + luma(200)))[
  #text(size: 9pt, weight: "bold", fill: luma(110))[CLICK #n · on screen:] #text(size: 10pt, fill: luma(90), style: "italic", screen) \\
  #say
]
#let watch(body) = block(inset: (y: 3pt))[#text(weight: "bold", fill: rgb("#b7791f"))[Point at:] #body]
#let background(body) = text(size: 10pt, fill: luma(90))[#text(weight: "bold")[Background:] #body]

#align(center)[
  #text(size: 22pt, weight: "bold")[Raft, one failure at a time] \\
  #v(2pt)
  #text(size: 13pt)[Speaker notes · D7024E seminar] \\
  #text(size: 10pt, fill: luma(110))[Review of Ongaro & Ousterhout, _In Search of an Understandable Consensus Algorithm_, USENIX ATC 2014 · raft.ronstad.se]
]

#v(8pt)
*How to use:* press → for each click. Each click below says what appears on screen and what to say. In the browser, press *S* for the speaker view (notes, timer, and a light that shows when the animation is done). Wait for "done" before clicking on demo slides.

=== Timing plan
#table(
  columns: (auto, 1fr, auto, auto),
  stroke: 0.5pt + luma(200),
  inset: 5pt,
  table.header([*\\#*], [*Slide*], [*Min*], [*Total*]),
${rows.join('\n')}
)
Optional slides can be skipped to save about ${mmss(SLIDES.filter(s => s.optional).reduce((a, s) => a + ((NOTES[s.title] || {}).min || 0), 0))} min.

#pagebreak()
${body.join('\n\n')}
`;

const dir = path.join(ROOT, 'notes');
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, 'speaker-notes.typ'), out);
console.log('wrote', path.join(dir, 'speaker-notes.typ'));
